"""Webhook endpoints and their delivery history (``client.webhooks``).

Every route needs the ``webhooks:write`` scope. The signing secret is generated by the server
and comes back on the answer of ``create`` only (``WebhookEndpoint.secret``, kept out of its
repr); no later call returns it. ``deliveries`` pages through the history of one endpoint,
``iter_deliveries`` follows the cursors, and ``redeliver`` requeues a ``failed`` or
``disabled`` delivery.
"""

from collections.abc import AsyncIterator, Iterator, Sequence
from typing import Any, Literal

from sandfort_sdk._requests import segment
from sandfort_sdk._transport import AsyncTransport, Reply, SyncTransport
from sandfort_sdk.models import _as_list, require_int_range
from sandfort_sdk.models_webhooks import DeliveryPage, WebhookDelivery, WebhookEndpoint

WEBHOOKS_PATH = "/v1/webhooks"
DEFAULT_LIMIT = 50
MIN_LIMIT = 1
MAX_LIMIT = 100
DeliveryState = Literal["pending", "delivered", "failed", "disabled"]
DELIVERY_STATES: tuple[str, ...] = ("pending", "delivered", "failed", "disabled")


def endpoint_path(endpoint_id: str) -> str:
    return f"{WEBHOOKS_PATH}/{segment(endpoint_id)}"


def deliveries_path(endpoint_id: str) -> str:
    return f"{endpoint_path(endpoint_id)}/deliveries"


def delivery_path(endpoint_id: str, delivery_id: str) -> str:
    return f"{deliveries_path(endpoint_id)}/{segment(delivery_id)}"


def _text(value: str, name: str) -> str:
    if not value.strip():
        raise ValueError(f"{name!r} must not be empty")
    return value


def _event_filters(events: Sequence[str]) -> list[str]:
    if isinstance(events, str):
        raise ValueError("'events' must be a sequence of event types, not one string")
    return [_text(event, "events entry") for event in events]


def create_body(url: str, events: Sequence[str], enabled: bool | None) -> dict[str, Any]:
    body: dict[str, Any] = {"url": _text(url, "url"), "event_types": _event_filters(events)}
    if enabled is not None:
        body["enabled"] = enabled
    return body


def update_body(
    url: str | None, events: Sequence[str] | None, enabled: bool | None
) -> dict[str, Any]:
    """Only the given fields; raises ``ValueError`` when there is nothing to change."""
    body: dict[str, Any] = {}
    if url is not None:
        body["url"] = _text(url, "url")
    if events is not None:
        body["event_types"] = _event_filters(events)
    if enabled is not None:
        body["enabled"] = enabled
    if not body:
        raise ValueError("nothing to update: pass url, events or enabled")
    return body


def deliveries_params(
    event_type: str | None, state: str | None, cursor: str | None, limit: int
) -> dict[str, Any]:
    """The query of a delivery list; raises ``ValueError`` before any request is made."""
    require_int_range(limit, "limit", MIN_LIMIT, MAX_LIMIT)
    if state is not None and state not in DELIVERY_STATES:
        raise ValueError(f"state must be one of {', '.join(DELIVERY_STATES)}; got {state!r}")
    params: dict[str, Any] = {}
    if event_type is not None:
        params["event_type"] = _text(event_type, "event_type")
    if state is not None:
        params["state"] = state
    if cursor is not None:
        params["cursor"] = _text(cursor, "cursor")
    params["limit"] = limit
    return params


def _endpoints(reply: Reply) -> tuple[WebhookEndpoint, ...]:
    items = _as_list(reply.data, "webhook endpoints")
    return tuple(WebhookEndpoint.from_payload(item) for item in items)


def _page(reply: Reply) -> DeliveryPage:
    items = _as_list(reply.data, "webhook deliveries")
    return DeliveryPage(tuple(WebhookDelivery.from_payload(i) for i in items), reply.next_cursor)


class Webhooks:
    """Synchronous webhook client."""

    def __init__(self, transport: SyncTransport) -> None:
        self._transport = transport

    def create(
        self, url: str, events: Sequence[str], *, enabled: bool | None = None
    ) -> WebhookEndpoint:
        """Register an endpoint; the answer carries the signing ``secret``, shown once.

        ``events``: event type filters such as ``"sandbox.started"``, ``"sandbox.*"`` or
        ``"*"``; an empty list is sent as is and the server decides what that selects.
        ``enabled`` is left out unless given (the server default applies). The server
        generates the secret, so the call takes none.
        """
        body = create_body(url, events, enabled)
        reply = self._transport.request("POST", WEBHOOKS_PATH, json=body)
        return WebhookEndpoint.from_payload(reply.data)

    def list(self) -> tuple[WebhookEndpoint, ...]:
        return _endpoints(self._transport.request("GET", WEBHOOKS_PATH))

    def get(self, endpoint_id: str) -> WebhookEndpoint:
        reply = self._transport.request("GET", endpoint_path(endpoint_id))
        return WebhookEndpoint.from_payload(reply.data)

    def update(
        self,
        endpoint_id: str,
        *,
        url: str | None = None,
        events: Sequence[str] | None = None,
        enabled: bool | None = None,
    ) -> WebhookEndpoint:
        """Change the given fields only; re-enabling an endpoint resets its failure count."""
        body = update_body(url, events, enabled)
        reply = self._transport.request("PATCH", endpoint_path(endpoint_id), json=body)
        return WebhookEndpoint.from_payload(reply.data)

    def delete(self, endpoint_id: str) -> WebhookEndpoint:
        """Delete an endpoint; the answer is the endpoint as it was."""
        reply = self._transport.request("DELETE", endpoint_path(endpoint_id))
        return WebhookEndpoint.from_payload(reply.data)

    def deliveries(
        self,
        endpoint_id: str,
        *,
        event_type: str | None = None,
        state: DeliveryState | None = None,
        cursor: str | None = None,
        limit: int = DEFAULT_LIMIT,
    ) -> DeliveryPage:
        """One page of an endpoint's deliveries in id order (``limit`` 1..100).

        ``event_type`` and ``state`` filter on the server; a cursor is bound to the endpoint
        and to those filters, so page on with the same ones. A filtered page may be short or
        empty while ``next_cursor`` is set: keep going until it is ``None``.
        """
        params = deliveries_params(event_type, state, cursor, limit)
        reply = self._transport.request("GET", deliveries_path(endpoint_id), params=params)
        return _page(reply)

    def iter_deliveries(
        self,
        endpoint_id: str,
        *,
        event_type: str | None = None,
        state: DeliveryState | None = None,
        limit: int = DEFAULT_LIMIT,
    ) -> Iterator[WebhookDelivery]:
        """Every delivery of :meth:`deliveries`, page by page, until there is no cursor."""
        cursor: str | None = None
        while True:
            page = self.deliveries(
                endpoint_id, event_type=event_type, state=state, cursor=cursor, limit=limit
            )
            yield from page.deliveries
            if page.next_cursor is None:
                return
            cursor = page.next_cursor

    def get_delivery(self, endpoint_id: str, delivery_id: str) -> WebhookDelivery:
        """One delivery with its outcome and attempt history."""
        reply = self._transport.request("GET", delivery_path(endpoint_id, delivery_id))
        return WebhookDelivery.from_payload(reply.data)

    def redeliver(self, endpoint_id: str, delivery_id: str) -> WebhookDelivery:
        """Requeue a ``failed`` or ``disabled`` delivery (any other state answers 409)."""
        path = f"{delivery_path(endpoint_id, delivery_id)}/redeliver"
        return WebhookDelivery.from_payload(self._transport.request("POST", path).data)


class AsyncWebhooks:
    """Asynchronous webhook client."""

    def __init__(self, transport: AsyncTransport) -> None:
        self._transport = transport

    async def create(
        self, url: str, events: Sequence[str], *, enabled: bool | None = None
    ) -> WebhookEndpoint:
        """Register an endpoint; the answer carries the signing ``secret``, shown once."""
        body = create_body(url, events, enabled)
        reply = await self._transport.request("POST", WEBHOOKS_PATH, json=body)
        return WebhookEndpoint.from_payload(reply.data)

    async def list(self) -> tuple[WebhookEndpoint, ...]:
        return _endpoints(await self._transport.request("GET", WEBHOOKS_PATH))

    async def get(self, endpoint_id: str) -> WebhookEndpoint:
        reply = await self._transport.request("GET", endpoint_path(endpoint_id))
        return WebhookEndpoint.from_payload(reply.data)

    async def update(
        self,
        endpoint_id: str,
        *,
        url: str | None = None,
        events: Sequence[str] | None = None,
        enabled: bool | None = None,
    ) -> WebhookEndpoint:
        """Change the given fields only; re-enabling an endpoint resets its failure count."""
        body = update_body(url, events, enabled)
        reply = await self._transport.request("PATCH", endpoint_path(endpoint_id), json=body)
        return WebhookEndpoint.from_payload(reply.data)

    async def delete(self, endpoint_id: str) -> WebhookEndpoint:
        """Delete an endpoint; the answer is the endpoint as it was."""
        reply = await self._transport.request("DELETE", endpoint_path(endpoint_id))
        return WebhookEndpoint.from_payload(reply.data)

    async def deliveries(
        self,
        endpoint_id: str,
        *,
        event_type: str | None = None,
        state: DeliveryState | None = None,
        cursor: str | None = None,
        limit: int = DEFAULT_LIMIT,
    ) -> DeliveryPage:
        """One page of an endpoint's deliveries; see :meth:`Webhooks.deliveries`."""
        params = deliveries_params(event_type, state, cursor, limit)
        reply = await self._transport.request("GET", deliveries_path(endpoint_id), params=params)
        return _page(reply)

    async def iter_deliveries(
        self,
        endpoint_id: str,
        *,
        event_type: str | None = None,
        state: DeliveryState | None = None,
        limit: int = DEFAULT_LIMIT,
    ) -> AsyncIterator[WebhookDelivery]:
        """Every delivery of :meth:`deliveries`, page by page, until there is no cursor."""
        cursor: str | None = None
        while True:
            page = await self.deliveries(
                endpoint_id, event_type=event_type, state=state, cursor=cursor, limit=limit
            )
            for item in page.deliveries:
                yield item
            if page.next_cursor is None:
                return
            cursor = page.next_cursor

    async def get_delivery(self, endpoint_id: str, delivery_id: str) -> WebhookDelivery:
        """One delivery with its outcome and attempt history."""
        reply = await self._transport.request("GET", delivery_path(endpoint_id, delivery_id))
        return WebhookDelivery.from_payload(reply.data)

    async def redeliver(self, endpoint_id: str, delivery_id: str) -> WebhookDelivery:
        """Requeue a ``failed`` or ``disabled`` delivery (any other state answers 409)."""
        path = f"{delivery_path(endpoint_id, delivery_id)}/redeliver"
        reply = await self._transport.request("POST", path)
        return WebhookDelivery.from_payload(reply.data)
